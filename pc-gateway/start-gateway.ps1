# ASCII-only body for start-gateway.ps1 (see README note).
# Reason: Windows PowerShell 5.1 decodes BOM-less .ps1 files as the system ANSI
# code page (GBK on this machine). Any multi-byte UTF-8 sequence whose byte pairs
# happen to hit a trailing quote (0x9D + 0x22) or backtick breaks the tokenizer,
# producing mojibake and parse errors. Keeping the script pure ASCII removes the
# whole class of problems; Chinese docs live in README.md instead.

[CmdletBinding()]
param(
  [int]$Port = 8765,
  [int]$DshPort = 3099,
  [string]$Profile = 'web',
  [string]$Cwd = '',
  [string]$LanHost = '',
  [switch]$TestHooks
)

$ErrorActionPreference = 'Stop'
# $PSScriptRoot is not available inside param default values, so resolve it here.
if (-not $Cwd) { $Cwd = (Split-Path -Parent (Split-Path -Parent $PSScriptRoot)) }
$StateDir = Join-Path $PSScriptRoot '.state'
$PluginDir = $PSScriptRoot
New-Item -ItemType Directory -Force $StateDir | Out-Null

function Fail($msg) { Write-Host "[gateway] ERROR: $msg" -ForegroundColor Red; exit 1 }

function PortInUse([int]$p) {
  $c = Get-NetTCPConnection -LocalPort $p -State Listen -ErrorAction SilentlyContinue
  if ($c) { return @($c)[0].OwningProcess }
  return $null
}

# --- 1. port check: fail loudly when busy, never silently switch ports ---
foreach ($pair in @(@{p=$Port; what='app gateway port'}, @{p=$DshPort; what='DSH instance port'})) {
  $owner = PortInUse $pair.p
  if ($owner) {
    Fail "$($pair.what) $($pair.p) is already in use by PID $owner. Run stop-gateway.ps1 first, or pass -Port/-DshPort."
  }
}
Write-Host "[gateway] port check OK: app=$Port dsh=$DshPort" -ForegroundColor DarkGray

# --- 2. token: 32 hex chars, persisted, stable across restarts ---
$TokenFile = Join-Path $StateDir 'token.txt'
if (-not (Test-Path $TokenFile)) {
  $bytes = New-Object byte[] 16
  $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
  $rng.GetBytes($bytes)
  $rng.Dispose()
  $t = -join ($bytes | ForEach-Object { $_.ToString('x2') })
  Set-Content -Path $TokenFile -Value $t -Encoding ascii -NoNewline
  Write-Host "[gateway] generated a new token in $TokenFile" -ForegroundColor Yellow
}
$Token = (Get-Content $TokenFile -Raw).Trim()
if ($Token -notmatch '^[0-9a-f]{32}$') { Fail "token.txt does not contain 32 hex chars" }
$Fp = $Token.Substring(0, 8)

# --- 3. generate the patch on the fly (absolute path derived from $PSScriptRoot) ---
# NOTE: a patch may only override an EXISTING entry by id; new entries must use a
#       top-level "- insert:" list. Hence one top-level entry carrying its own config.
$Entry = 'file:///' + ((Join-Path $PluginDir 'index.js') -replace '\\', '/')
if ($TestHooks) { $env:DSH_RC_TEST_HOOKS = '1' } else { Remove-Item Env:\DSH_RC_TEST_HOOKS -ErrorAction SilentlyContinue }
$PatchFile = Join-Path $StateDir 'gateway.patch.yml'
$PortLit = [string]$Port
$CwdLit = $Cwd -replace "'", "''"
$HooksLit = if ($TestHooks) { 'true' } else { 'false' }
$LanHostLit = if ($LanHost) { "'" + $LanHost + "'" } else { 'null' }
@"
# Auto-generated by start-gateway.ps1 on every start. Do not edit by hand.
- insert:
    - id: remote-gateway
      name: '$Entry'
      config:
        host: '0.0.0.0'
        port: $PortLit
        defaultCwd: '$CwdLit'
        lanHost: !!js $LanHostLit
        testHooks: !!js $HooksLit
"@ | Set-Content -Path $PatchFile -Encoding utf8
Write-Host "[gateway] patch written: $PatchFile" -ForegroundColor DarkGray

# --- 4. launch the second DSH instance in the background ---
$LogFile = Join-Path $StateDir 'dsh-instance.log'
Write-Host "[gateway] starting DSH instance (profile=$Profile port=$DshPort) ..."
$proc = Start-Process -FilePath 'cmd.exe' `
  -ArgumentList '/c', "dsh --profile $Profile --patch `"$PatchFile`" --port $DshPort --no-open > `"$LogFile`" 2>&1" `
  -PassThru -WindowStyle Hidden
Write-Host "[gateway] DSH launcher PID=$($proc.Id) log=$LogFile" -ForegroundColor DarkGray

# --- 5. poll /rc/v1/ping until ready ---
$ready = $false
for ($i = 0; $i -lt 120; $i++) {
  Start-Sleep -Seconds 1
  try {
    $r = Invoke-RestMethod -Uri "http://127.0.0.1:$Port/rc/v1/ping" -TimeoutSec 2
    if ($r.v -eq 1) { $ready = $true; break }
  } catch { }
}
if (-not $ready) {
  Write-Host "[gateway] ERROR: gateway was not ready within 120s. Last log lines:" -ForegroundColor Red
  if (Test-Path $LogFile) { Get-Content $LogFile -Tail 40 | ForEach-Object { Write-Host "  $_" -ForegroundColor DarkGray } }
  exit 1
}
Write-Host "[gateway] gateway is ready (ping OK)" -ForegroundColor Green

# --- 6. LAN address + state file ---
# The authoritative choice lives in the plugin (lib/http.mjs selectLanIpv4, which
# excludes loopback / link-local / virtual adapters). The plugin writes its pick to
# .state/runtime.json; read it back instead of re-implementing the logic in
# PowerShell (the old inline version re-hit the VMware-adapter trap).
$RuntimeFile = Join-Path $StateDir 'runtime.json'
$peer = $null
for ($i = 0; $i -lt 20; $i++) {
  if (Test-Path $RuntimeFile) {
    try {
      $rt = Get-Content $RuntimeFile -Raw -Encoding UTF8 | ConvertFrom-Json
      if ($rt.peer) { $peer = $rt.peer; break }
    } catch { }
  }
  Start-Sleep -Milliseconds 500
}
if (-not $peer) {
  Write-Host '[gateway] WARN: could not read the selected address from runtime.json' -ForegroundColor Yellow
  $peer = if ($LanHost) { $LanHost } else { '127.0.0.1' }
}
if ($LanHost -and $peer -ne $LanHost) {
  Write-Host "[gateway] forcing -LanHost $LanHost (auto-picked $peer)" -ForegroundColor Yellow
  $peer = $LanHost
}

$StateFile = Join-Path $StateDir 'gateway.json'
@{
  host    = $peer
  port    = $Port
  token   = $Token
  fp      = $Fp
  pid     = $proc.Id
  startedAt = [DateTimeOffset]::UtcNow.ToUnixTimeMilliseconds()
} | ConvertTo-Json | Set-Content -Path $StateFile -Encoding utf8
Write-Host "[gateway] state file: $StateFile" -ForegroundColor DarkGray

# --- 7. pairing QR payload (spec 3.4, single-line JSON) ---
$Payload = '{"v":1,"name":"' + $env:COMPUTERNAME + '","host":"' + $peer + '","port":' + $Port +
           ',"token":"' + $Token + '","fp":"' + $Fp + '"}'
Set-Content -Path (Join-Path $StateDir 'pairing.json.txt') -Value $Payload -Encoding utf8
Write-Host ''
Write-Host "  Pairing payload (scan it, or type it in the app):" -ForegroundColor Cyan
Write-Host "  $Payload" -ForegroundColor White
Write-Host ''

$QrScript = Join-Path $PluginDir 'print-qr.mjs'
if (Test-Path $QrScript) {
  & node $QrScript $Payload
} else {
  Write-Host '  [warn] print-qr.mjs not found, skipping the QR drawing' -ForegroundColor Yellow
}

Write-Host ''
Write-Host "[gateway] RUNNING: http://$peer`:$Port  WS: ws://$peer`:$Port/rc/v1/stream?token=<token>" -ForegroundColor Green
Write-Host "[gateway] stop with: $PSScriptRoot\stop-gateway.cmd" -ForegroundColor DarkGray
exit 0
